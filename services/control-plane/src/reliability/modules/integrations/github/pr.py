"""Deterministic pull requests for verified, approved repairs (ADR-0017, agent-workflows §6).

The body is a fixed template filled with facts (finding, hypothesis, evidence links, gate
table, comparison with confidence intervals, regression test) plus the agent's explanation,
labelled as AI-generated. A ``pull_requests`` row is created before calling GitHub
(``repair_attempt_id`` is unique), so a retried job never opens a second PR. The GitHub App
can create a branch, a commit and a pull request — never merge or push to existing branches.
"""

from __future__ import annotations

import uuid
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from reliability.modules.integrations.github import service as github
from reliability.modules.integrations.github.client import BRANCH_PREFIX, get_client
from reliability.modules.integrations.github.models import PullRequest, Repository
from reliability.platform.errors import AppError
from reliability.platform.ids import uuid7
from reliability.platform.settings import get_settings

DISCLAIMER = (
    "This change was generated by an AI agent and verified automatically in an isolated sandbox "
    "(see the gates below). It has not been reviewed by a person yet: review it like any other "
    "contribution before merging."
)


def branch_name(finding_id: uuid.UUID, attempt_id: uuid.UUID) -> str:
    return f"{BRANCH_PREFIX}{str(finding_id)[:8]}-{str(attempt_id)[:8]}"


def title(finding_title: str) -> str:
    return f"fix(reliability): {finding_title}"[:240]


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.3g}"
    return str(v)


def render_body(
    *,
    project_id: uuid.UUID,
    finding: dict[str, Any],
    hypothesis: dict[str, Any],
    evidence: list[dict[str, Any]],
    gates: list[dict[str, Any]],
    comparisons: list[dict[str, Any]],
    test_paths: list[str],
    explanation: str,
    diff_stats: dict[str, Any] | None,
) -> str:
    web = get_settings().web_base_url.rstrip("/")
    finding_url = f"{web}/projects/{project_id}/findings/{finding['id']}"
    lines = [
        "## Finding",
        f"**{finding['title']}** ({finding.get('severity', '')}, {finding.get('type', '').replace('_', ' ')}) — "
        f"[open in Reliability Engineer]({finding_url})",
        "",
        *(f"- {k.replace('_', ' ')}: {_fmt(v)}" for k, v in (finding.get("headline") or {}).items()),
        "",
        "## Root-cause hypothesis",
        f"{hypothesis.get('statement', '')}",
        "",
        f"Category: `{hypothesis.get('category')}` · confidence **{hypothesis.get('confidence')}** "
        f"(score {_fmt((hypothesis.get('confidence_factors') or {}).get('score', '—'))}, "
        f"{(hypothesis.get('confidence_factors') or {}).get('rubric_version', '')})",
        "",
        "Evidence:",
        *(
            f"- [{e['kind'].replace('_', ' ')}]({finding_url}#evidence-{e['id']}): {e['summary']}"
            for e in evidence[:10]
        ),
        "",
        "## Verification gates",
        "| Gate | Result | Details |",
        "|---|---|---|",
    ]
    for g in gates:
        res = g.get("result") or {}
        detail = res.get("reason") or res.get("note") or ""
        if g["gate"] == "fail_to_pass" and "base_exit_codes" in res:
            detail = f"base exit codes {res['base_exit_codes']}, patched {res['patched_exit_codes']}"
        if g["gate"] == "diff_policy" and res.get("stats"):
            detail = (
                f"{res['stats'].get('files')} files, +{res['stats'].get('additions')}/-{res['stats'].get('deletions')}"
            )
        if g["gate"] == "security":
            detail = f"scanners: {', '.join(res.get('scanners') or [])}"
        lines.append(
            f"| {g['gate'].replace('_', ' ')} | {g['status']}{'' if g['applicable'] else ' (n/a)'} | {detail} |"
        )
    if comparisons:
        lines += [
            "",
            "## Before / after (sandbox, interleaved runs)",
            "| Scope | Metric | Before | After | Change | 95% CI | Noise floor | Verdict |",
            "|---|---|---|---|---|---|---|---|",
            *(
                f"| {c['scope']} | {c['metric']} | {c['baseline_value']:.1f} | {c['candidate_value']:.1f} | "
                f"{c['delta_pct']:+.1f}% | [{c['ci_low_pct']:+.1f}%, {c['ci_high_pct']:+.1f}%] | "
                f"±{c['noise_floor_pct']:.1f}% | {c['verdict']} |"
                for c in comparisons
            ),
            "",
            "Statistic: relative change of the median per-run p95 (BCa bootstrap, requests resampled within runs).",
        ]
    lines += [
        "",
        "## Regression test",
        *(f"- `{p}` — fails on the base commit (3/3) and passes with this change (3/3)" for p in test_paths),
        "",
        "## Explanation (AI-generated)",
        explanation.strip() or "_No explanation provided._",
        "",
        f"_{DISCLAIMER}_",
    ]
    if diff_stats:
        lines.insert(0, f"<!-- reliability-engineer: {diff_stats} -->")
    return "\n".join(lines)[:60000]


async def existing(session: AsyncSession, repair_attempt_id: uuid.UUID) -> PullRequest | None:
    return (
        await session.execute(select(PullRequest).where(PullRequest.repair_attempt_id == repair_attempt_id))
    ).scalar_one_or_none()


async def reserve(
    session: AsyncSession, *, org_id: uuid.UUID, repair_attempt_id: uuid.UUID, repository: Repository, branch: str
) -> PullRequest:
    """Create the row first (unique per attempt): a retried job finds it instead of opening another PR."""
    pr = await existing(session, repair_attempt_id)
    if pr is not None:
        return pr
    pr = PullRequest(
        id=uuid7(),
        org_id=org_id,
        repair_attempt_id=repair_attempt_id,
        repository_id=repository.id,
        branch=branch,
        state="creating",
    )
    session.add(pr)
    await session.flush()
    return pr


async def open_pull_request(
    session: AsyncSession,
    pr: PullRequest,
    repository: Repository,
    *,
    base_sha: str,
    files: dict[str, str | None],
    pr_title: str,
    body: str,
) -> PullRequest:
    if pr.state == "open":
        return pr
    try:
        token = await github.job_token(session, repository, write=True)
        client = get_client()
        await client.create_branch_with_changes(
            token, repository.full_name, base_sha, pr.branch, files, f"{pr_title}\n\nGenerated by Reliability Engineer."
        )
        data = await client.open_pull_request(
            token, repository.full_name, pr.branch, repository.default_branch, pr_title, body
        )
    except AppError as exc:
        pr.state, pr.error = "failed", exc.message[:500]
        return pr
    pr.state, pr.number, pr.url, pr.error = "open", int(data["number"]), str(data.get("html_url") or ""), None
    return pr
