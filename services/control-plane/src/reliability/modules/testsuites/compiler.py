"""Deterministic compilation of Workflow IR into k6 and Playwright bundles (ADR-0012, ADR-0013).

Generated files embed each workflow as JSON data and call a fixed runtime (assets/), so
workflow content is never spliced into code. The same IR always yields byte-identical
files, which makes suites reproducible and reviewable.
"""

from __future__ import annotations

import hashlib
import io
import json
import re
import tarfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from reliability.modules.workflows.ir import api_steps

ASSETS = Path(__file__).with_name("assets")
RUNTIME_VERSION = "1"


def fn_name(key: str, taken: set[str]) -> str:
    base = "wf_" + re.sub(r"[^a-z0-9_]", "_", key)
    name, n = base, 2
    while name in taken:
        name, n = f"{base}_{n}", n + 1
    taken.add(name)
    return name


def _json(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)


@dataclass
class CompiledCase:
    workflow_key: str
    type: str  # playwright | k6_scenario | k6_probe
    path: str
    exec_name: str | None = None
    invariant_id: str | None = None


@dataclass
class Bundle:
    files: dict[str, str] = field(default_factory=dict)
    cases: list[CompiledCase] = field(default_factory=list)
    exec_names: dict[str, str] = field(default_factory=dict)  # workflow key -> k6 exec fn

    def manifest(self) -> dict[str, Any]:
        return {
            "runtime_version": RUNTIME_VERSION,
            "files": {p: hashlib.sha256(c.encode()).hexdigest() for p, c in sorted(self.files.items())},
            "exec_names": self.exec_names,
            "cases": [c.__dict__ for c in self.cases],
        }

    def tarball(self, prefix: str) -> bytes:
        """Deterministic .tar.gz of files under ``prefix/`` (e.g. "k6" or "playwright")."""
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w:gz", compresslevel=6) as tar:
            for path in sorted(p for p in self.files if p.startswith(prefix + "/")):
                data = self.files[path].encode()
                info = tarfile.TarInfo(path[len(prefix) + 1 :])
                info.size, info.mtime, info.mode = len(data), 0, 0o644
                tar.addfile(info, io.BytesIO(data))
        return buf.getvalue()


def compile_bundle(workflows: list[dict[str, Any]]) -> Bundle:
    """``workflows``: list of Workflow IR dicts (already validated, approved)."""
    bundle = Bundle()
    taken: set[str] = set()
    k6_imports, k6_exports = [], []
    bundle.files["k6/lib/runtime.js"] = (ASSETS / "k6_runtime.js").read_text()
    bundle.files["playwright/runtime.ts"] = (ASSETS / "pw_runtime.ts").read_text()
    bundle.files["playwright/playwright.config.ts"] = (ASSETS / "playwright.config.ts").read_text()

    for ir in sorted(workflows, key=lambda w: w["key"]):
        name = fn_name(ir["key"], taken)
        if api_steps(ir):
            path = f"k6/workflows/{name}.js"
            bundle.files[path] = f"// Workflow IR {ir['key']} (generated — do not edit)\nexport default {_json(ir)};\n"
            k6_imports.append(f'import {name}_ir from "./workflows/{name}.js";')
            k6_exports.append(f"export function {name}() {{\n  runWorkflow({name}_ir);\n}}")
            bundle.exec_names[ir["key"]] = name
            bundle.cases.append(CompiledCase(ir["key"], "k6_scenario", path, exec_name=name))
            for inv in ir.get("invariants", []):
                probe_path = f"k6/probes/{name}__{inv['id']}.js"
                bundle.files[probe_path] = _probe(name, ir, inv)
                bundle.cases.append(CompiledCase(ir["key"], "k6_probe", probe_path, invariant_id=inv["id"]))
        if ir["kind"] == "browser":
            path = f"playwright/tests/{name}.spec.ts"
            bundle.files[path] = (
                f"// Workflow IR {ir['key']} (generated — do not edit)\n"
                'import { test } from "@playwright/test";\n'
                'import { runWorkflow } from "../runtime";\n\n'
                f"const WORKFLOW = {_json(ir)};\n\n"
                f"test({json.dumps(ir['title'])}, {{ tag: [{json.dumps('@' + ir['criticality'])}] }}, "
                "async ({ page }) => {\n  await runWorkflow(page, WORKFLOW);\n});\n"
            )
            bundle.cases.append(CompiledCase(ir["key"], "playwright", path))

    first = next(iter(bundle.exec_names.values()), None)
    bundle.files["k6/scenarios.js"] = "\n".join(
        [
            "// Generated by Reliability Engineer — scenarios are selected by options.json (per run).",
            'import { runWorkflow } from "./lib/runtime.js";',
            *k6_imports,
            "",
            'export const options = JSON.parse(open("./options.json"));',
            "",
            *k6_exports,
            "",
            f"export default function () {{\n  {first + '();' if first else '/* no API workflows */'}\n}}",
            "",
        ]
    )
    bundle.files["manifest.json"] = _json(bundle.manifest())
    return bundle


_OPS = {"==": "===", "!=": "!==", ">=": ">=", "<=": "<=", ">": ">", "<": "<"}


def _probe(name: str, ir: dict[str, Any], inv: dict[str, Any]) -> str:
    steps = api_steps(ir)
    idx = next(i for i, s in enumerate(steps) if s["id"] == inv["step_ref"])
    before = [s["id"] for s in steps[:idx]]
    expect = inv.get("expect_successes") or {}
    thresholds: dict[str, list[str]] = {"checks": ["rate==1"]}
    bounds = []
    if "max" in expect:
        bounds.append(f"count<={int(expect['max'])}")
    if "min" in expect:
        bounds.append(f"count>={int(expect['min'])}")
    if bounds:
        thresholds["probe_successes"] = bounds
    options = {
        "scenarios": {
            "probe": {
                "executor": "shared-iterations",
                "vus": inv["parallel"],
                "iterations": inv["parallel"],
                "maxDuration": "60s",
            }
        },
        "thresholds": thresholds,
    }
    return "\n".join(
        [
            f"// Concurrency probe {inv['id']} for {ir['key']} (generated — do not edit)",
            'import http from "k6/http";',
            'import { check } from "k6";',
            'import { Counter } from "k6/metrics";',
            'import { BASE_URL, findStep, initVars, jsonGet, login, render, request } from "../lib/runtime.js";',
            f'import WF from "../workflows/{name}.js";',
            "",
            f"const INV = {_json(inv)};",
            f"const BEFORE = {json.dumps(before)};",
            'const successes = new Counter("probe_successes");',
            f"export const options = {_json(options)};",
            "",
            "export function setup() {",
            "  const vars = initVars(WF);",
            "  login(WF, vars);",
            "  for (const id of BEFORE) request(WF, findStep(WF, id), vars);",
            "  return vars;",
            "}",
            "",
            "export default function (data) {",
            "  const vars = Object.assign({}, data);",
            "  const res = request(WF, findStep(WF, INV.step_ref), vars);",
            "  if (res.status >= 200 && res.status < 300) successes.add(1);",
            "}",
            "",
            "export function teardown(data) {",
            "  const req = render(INV.check.request, data);",
            "  const res = http.request(req.method, `${BASE_URL}${req.path}`, null, { tags: { probe: INV.id } });",
            "  let observed;",
            "  try { observed = jsonGet(res.json(), INV.check.jsonpath); } catch (e) { observed = undefined; }",
            f"  check(observed, {{ [`invariant ${{INV.id}}`]: (v) => v {_OPS[inv['check']['op']]} INV.check.value }});",
            "}",
            "",
        ]
    )
